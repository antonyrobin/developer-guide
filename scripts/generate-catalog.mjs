/**
 * Generates src/data/catalog.generated.js — the lightweight course metadata the
 * app needs up-front (navigation, home cards, instant title search). Full course
 * content is loaded lazily per course, so the initial bundle stays small.
 *
 * Runs automatically before `npm run dev` and `npm run build`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { mergeCourse } from '../src/data/mergeCourse.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = path.join(root, 'src/data/courses-data');
const extDir = path.join(root, 'src/data/course-extensions');
const outFile = path.join(root, 'src/data/catalog.generated.js');

const entries = {};
for (const file of fs.readdirSync(dataDir).filter(f => f.endsWith('.js')).sort()) {
  const mod = await import(pathToFileURL(path.join(dataDir, file)).href);
  const base = Object.values(mod).find(v => v && typeof v === 'object' && v.id && v.sections);
  if (!base) throw new Error(`No course export found in ${file}`);

  const extFile = path.join(extDir, `${base.id}.js`);
  const ext = fs.existsSync(extFile) ? (await import(pathToFileURL(extFile).href)).default : null;
  const course = mergeCourse(base, ext);

  if (entries[course.id]) throw new Error(`Duplicate course id "${course.id}" in ${file}`);
  entries[course.id] = {
    id: course.id,
    file: file.replace(/\.js$/, ''),
    title: course.title,
    description: course.description,
    sectionCount: course.sections.length,
  };
}

const banner = '// AUTO-GENERATED by scripts/generate-catalog.mjs — do not edit by hand.\n';
fs.writeFileSync(outFile, `${banner}export const catalog = ${JSON.stringify(entries, null, 2)};\n`);
console.log(`catalog: ${Object.keys(entries).length} courses -> ${path.relative(root, outFile)}`);
